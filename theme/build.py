# ── build helpers ───────────────────────────────────────────────────────
def qcss(c):                     # Qt stylesheets: alpha as a percentage (0.4 would read as 0)
    r, g, b, a = parse(c)
    return f"#{r:02x}{g:02x}{b:02x}" if a >= 0.999 else f"rgba({r}, {g}, {b}, {round(a * 100)}%)"


def hyp(c):                      # Hyprland / hyprlock
    return f"rgba({hx8(c)[1:]})"


def qargb(c):                    # Qt: #AARRGGBB
    r, g, b, a = parse(c)
    return f"#{round(a * 255):02x}{r:02x}{g:02x}{b:02x}"


def banner(mark="#"):
    end = {"/*": " */", "<!--": " -->"}.get(mark, "")
    return f"{mark} GENERATED by theme/build.py from theme/tokens.toml. Edit the tokens, not this file.{end}\n"


def write(rel, text):
    p = ROOT / rel
    old = p.read_text() if p.exists() else None
    if old == text:
        return
    changed.append(rel)
    if not CHECK:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


