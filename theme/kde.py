"""KDE Plasma: the second session, in the look.

Hyprland tiles; Plasma (picked at the sign-in screen) is the full desktop with its own panel,
settings and apps. It keeps its own shell; this module dresses it in each edition:

  kde/.local/share/color-schemes/Fui<Edition>.colors      every KDE app's colours: keys are
        chrome faces printed in the dark mark, the selection is the signal, headers are chrome
  kde/.local/share/aurorae/themes/fui-<edition>/           the window frame (Aurorae, SVG): a
        unified chrome title bar, the title left in the mono voice, square gel keys (red gel for
        close), boxy 4 px corners, a soft shadow
  kde/.local/share/plasma/desktoptheme/fui-<edition>/      the Plasma style: the panel and pop-ups
        as round chrome shells (the parts on them stay Plasma's own, in the scheme's colours)

`fui plasma apply` (run at Plasma sign-in and by `fui mode` inside Plasma) points Plasma at
the current edition's, sets the cursor and the wallpaper.
"""
from palette import EDS, LOOK, TOK, contrast, full, is_dark, mix

F = TOK["font"]


def rgb(c):
    h = c.lstrip("#")
    return ",".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))


def hx(c):
    return "#" + c.lstrip("#")[:6].upper()


def camel(ed):
    return "Fui" + ed.capitalize()


# ── the colour scheme ───────────────────────────────────────────────────
def colors(ed):
    p = full(ed)
    def group(bg, alt, fg, inactive):
        return (f"BackgroundNormal={rgb(bg)}\nBackgroundAlternate={rgb(alt)}\n"
                f"ForegroundNormal={rgb(fg)}\nForegroundInactive={rgb(inactive)}\nForegroundActive={rgb(p['signal_hi'])}\n"
                f"ForegroundLink={rgb(p['info'])}\nForegroundVisited={rgb(p['info'])}\n"
                f"ForegroundNegative={rgb(p['bad'])}\nForegroundNeutral={rgb(p['warn'])}\nForegroundPositive={rgb(p['ok'])}\n"
                f"DecorationFocus={rgb(p['signal'])}\nDecorationHover={rgb(p['signal_hi'])}\n")
    title = max((p["ink"], p["mark"]), key=lambda c: contrast(c, p["chrome_mid"]))
    return (f"# GENERATED by theme/build.py from theme/tokens.toml (theme/kde.py).\n"
            f"[ColorEffects:Disabled]\nColor={rgb(p['panel'])}\nColorAmount=0\nColorEffect=0\nContrastAmount=0.65\nContrastEffect=1\n"
            f"IntensityAmount=0.1\nIntensityEffect=2\n\n"
            f"[ColorEffects:Inactive]\nChangeSelectionColor=true\nColor={rgb(p['panel'])}\nColorAmount=0.025\nColorEffect=2\n"
            f"ContrastAmount=0.1\nContrastEffect=2\nEnable=false\nIntensityAmount=0\nIntensityEffect=0\n\n"
            f"[Colors:Button]\n" + group(p["face_mid"], p["face_hi"], p["mark"], p["mark_off"]) + "\n"
            f"[Colors:Complementary]\n" + group(p["floor"], p["panel"], p["ink"], p["muted"]) + "\n"
            f"[Colors:Header]\n" + group(p["chrome_mid"], p["chrome_top"], title, p["chrome_ink_off"]) + "\n"
            f"[Colors:Header][Inactive]\n" + group(p["chrome_horizon"], p["chrome_mid"], p["chrome_ink_off"], p["chrome_ink_off"]) + "\n"
            f"[Colors:Selection]\n" + group(p["signal"], p["signal_hi"], p["on_signal"], p["on_signal"]) + "\n"
            f"[Colors:Tooltip]\n" + group(p["raised"], p["panel"], p["ink"], p["muted"]) + "\n"
            f"[Colors:View]\n" + group(p["well"], p["panel"], p["ink"], p["muted"]) + "\n"
            f"[Colors:Window]\n" + group(p["floor"], p["panel"], p["ink"], p["muted"]) + "\n"
            f"[General]\nColorScheme={camel(ed)}\nName=fui {ed}\nshadeSortColumn=true\n\n"
            f"[KDE]\ncontrast=4\n\n"
            f"[WM]\nactiveBackground={rgb(p['chrome_mid'])}\nactiveBlend={rgb(p['chrome_top'])}\nactiveForeground={rgb(title)}\n"
            f"inactiveBackground={rgb(p['chrome_horizon'])}\ninactiveBlend={rgb(p['chrome_mid'])}\n"
            f"inactiveForeground={rgb(p['chrome_ink_off'])}\n")


# ── the window frame (Aurorae) ──────────────────────────────────────────
TITLE, EDGE, BORDER, BTN = 22, 4, 4, 18            # px: the title row, its edges, the chassis border (= the corner), a key
TOP = EDGE + TITLE + EDGE


def _grad(gid, stops):
    return (f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="1">'
            + "".join(f'<stop offset="{o}" stop-color="{hx(c)}"/>' for o, c in stops) + "</linearGradient>")


def decoration(ed):
    """decoration.svg: the frame in nine pieces (FrameSvg), active and inactive. The top row is
    unified chrome; the corners round at the look's 4 px, which is also the side and bottom
    border (the chassis), so every corner piece is as wide as the side beside it."""
    p = full(ed)
    r = BORDER
    W = 2 * r + 8                                  # the tile: two corners and a stretchable middle
    defs = _grad("a", [(0, p["chrome_top"]), (0.55, p["chrome_mid"]), (1, p["chrome_low"])]) + \
        _grad("i", [(0, p["chrome_mid"]), (1, p["chrome_horizon"])]) + \
        _grad("s", [(0, p["chrome_low"]), (1, mix(p["chrome_low"], "#000000", 0.2))])
    rim, lip = hx(p["rim"]), hx(p["chrome_lip"])
    parts = []
    for prefix, g, side in (("decoration", "a", "url(#s)"), ("decoration-inactive", "i", hx(p["chrome_horizon"]))):
        y = 0 if g == "a" else 100
        edge = f'<rect x="{r}" y="{y + 0.5}" width="8" height="1" fill="{lip}" opacity="0.9"/>' if g == "a" else ""
        parts += [
            f'<g id="{prefix}-topleft"><path d="M0,{y + TOP} V{y + r} Q0,{y} {r},{y} V{y + TOP} Z" fill="url(#{g})"/>'
            f'<path d="M0.5,{y + TOP} V{y + r} Q0.5,{y + 0.5} {r},{y + 0.5}" fill="none" stroke="{rim}"/></g>',
            f'<g id="{prefix}-top"><rect x="{r}" y="{y}" width="8" height="{TOP}" fill="url(#{g})"/>{edge}'
            f'<path d="M{r},{y + 0.5} H{r + 8}" stroke="{rim}" opacity="0.6"/></g>',
            f'<g id="{prefix}-topright"><path d="M{W},{y + TOP} V{y + r} Q{W},{y} {W - r},{y} V{y + TOP} Z" fill="url(#{g})"/>'
            f'<path d="M{W - 0.5},{y + TOP} V{y + r} Q{W - 0.5},{y + 0.5} {W - r},{y + 0.5}" fill="none" stroke="{rim}"/></g>',
            f'<rect id="{prefix}-left" x="0" y="{y + TOP}" width="{r}" height="8" fill="{side}"/>',
            f'<rect id="{prefix}-center" x="{r}" y="{y + TOP}" width="8" height="8" fill="{hx(p["floor"])}"/>',
            f'<rect id="{prefix}-right" x="{W - r}" y="{y + TOP}" width="{r}" height="8" fill="{side}"/>',
            f'<rect id="{prefix}-bottomleft" x="0" y="{y + TOP + 8}" width="{r}" height="{r}" fill="{side}"/>',
            f'<rect id="{prefix}-bottom" x="{r}" y="{y + TOP + 8}" width="8" height="{r}" fill="{side}"/>',
            f'<rect id="{prefix}-bottomright" x="{W - r}" y="{y + TOP + 8}" width="{r}" height="{r}" fill="{side}"/>',
        ]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{100 + TOP + 8 + r}">'
            f"<defs>{defs}</defs>{''.join(parts)}</svg>\n")


def _glyph(name, colour):
    w = f'stroke="{colour}" stroke-width="1.8" stroke-linecap="round" fill="none"'
    return {
        "minimize": f'<path d="M6 12.5h6" {w}/>',
        "maximize": f'<rect x="5.5" y="5.5" width="7" height="7" rx="0.8" {w}/>',
        "restore": f'<path d="M7.5 5.5h5v5" {w}/><rect x="5.5" y="7.5" width="5" height="5" rx="0.8" {w}/>',
        "close": f'<path d="M6 6l6 6M12 6l-6 6" {w}/>',
    }[name]


def button(ed, name):
    """One key, five states (FrameSvg prefixes active, hover, pressed, inactive, deactivated):
    a square chrome key (red gel for close) with a specular band, the glyph printed on it."""
    p = full(ed)
    cr = LOOK["control"]
    bad = p["bad"]
    if name == "close":
        body = [(0, mix(bad, "#FFFFFF", 0.45)), (0.48, mix(bad, "#FFFFFF", 0.15)), (0.52, bad), (1, mix(bad, "#000000", 0.35))]
        mark = "#FFFFFF"
    else:
        body = [(0, p["face_hi"]), (0.48, p["face_mid"]), (0.52, p["face_horizon"]), (1, p["face_lo"])]
        mark = hx(p["mark"])
    quiet = [(0, p["chrome_top"]), (1, p["chrome_mid"])]
    defs = _grad("b", body) + _grad("q", quiet) + \
        '<linearGradient id="l" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#FFFFFF" stop-opacity="0.7"/>' \
        '<stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></linearGradient>'
    states = []
    for i, (state, fill, glow, gcol) in enumerate((("active", "b", 0, mark), ("hover", "b", 1, mark), ("pressed", "b", 0, mark),
                                                    ("inactive", "q", 0, hx(p["chrome_ink_off"])),
                                                    ("deactivated", "q", 0, hx(p["chrome_ink_off"])))):
        x = i * (BTN + 2)
        halo = (f'<rect x="{x}" y="0" width="{BTN}" height="{BTN}" rx="{cr + 1}" fill="{hx(bad if name == "close" else p["signal"])}" opacity="0.35"/>'
                if glow else "")
        shade = '<rect x="{0}" y="1.5" width="{1}" height="{1}" rx="{2}" fill="#000000" opacity="0.18"/>'.format(x + 1.5, BTN - 3, cr) \
            if state == "pressed" else ""
        states.append(
            f'<g id="{state}-center">{halo}'
            f'<rect x="{x + 1.5}" y="1.5" width="{BTN - 3}" height="{BTN - 3}" rx="{cr}" fill="url(#{fill})" stroke="{hx(p["rim"])}" stroke-width="1"/>'
            f'<rect x="{x + 2.5}" y="2.5" width="{BTN - 5}" height="{(BTN - 5) * 0.45:.1f}" rx="{max(cr - 1, 0)}" fill="url(#l)"/>{shade}'
            f'<g transform="translate({x},0)">{_glyph(name, gcol)}</g></g>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{5 * (BTN + 2)}" height="{BTN}">'
            f"<defs>{defs}</defs>{''.join(states)}</svg>\n")


def aurorae(ed):
    """The files of one Aurorae theme: {name: text}."""
    p = full(ed)
    title = max((p["ink"], p["mark"]), key=lambda c: contrast(c, p["chrome_mid"]))
    name = f"fui-{ed}"
    files = {
        "metadata.desktop": f"[Desktop Entry]\nName=fui {ed}\nComment=Chrome title bar, square gel keys (theme/kde.py)\n"
                            f"X-KDE-PluginInfo-Name={name}\nX-KDE-PluginInfo-Version=1\nX-KDE-PluginInfo-License=MIT\n"
                            f"X-KDE-PluginInfo-EnabledByDefault=true\nX-Plasma-API=declarativeappletscript\n",
        f"{name}rc": f"[General]\nActiveTextColor={hx(title)}\nInactiveTextColor={hx(p['chrome_ink_off'])}\n"
                     f"TitleAlignment=Left\nTitleVerticalAlignment=Center\nAnimation=120\nUseTextShadow=false\nShadow=true\n"
                     f"DecorationPosition=0\n\n[Layout]\nBorderLeft={BORDER}\nBorderRight={BORDER}\nBorderBottom={BORDER}\n"
                     f"TitleEdgeTop={EDGE}\nTitleEdgeBottom={EDGE}\nTitleEdgeLeft=8\nTitleEdgeRight=6\nTitleHeight={TITLE}\n"
                     f"TitleEdgeTopMaximized={EDGE}\nTitleEdgeBottomMaximized={EDGE}\nTitleEdgeLeftMaximized=8\nTitleEdgeRightMaximized=6\n"
                     f"TitleBorderLeft=6\nTitleBorderRight=6\nButtonWidth={BTN}\nButtonHeight={BTN}\nButtonSpacing=3\n"
                     f"ButtonMarginTop={(TITLE - BTN) // 2}\nExplicitButtonSpacer=8\nPaddingTop=0\nPaddingBottom=0\nPaddingLeft=0\nPaddingRight=0\n",
        "decoration.svg": decoration(ed),
    }
    for b in ("close", "minimize", "maximize", "restore"):
        files[f"{b}.svg"] = button(ed, b)
    return files


# ── the Plasma style: the panel and the pop-ups as round chrome shells ──
def _shell_svg(p, radius, stops, rim, element_prefixes=("",)):
    """A FrameSvg background in nine pieces per prefix (the panel has one set per screen edge).
    Plasma draws each piece by its id, so every piece carries its own part of the shape: the
    corners are quarter discs, the edges and the middle rectangles, all filled from one
    gradient laid across the whole shell, the rim stroked along the outside only."""
    R, M = radius, 8
    S = 2 * R + M
    out, defs = [], []
    for n, pre in enumerate(element_prefixes):
        y = n * (S + 4)
        pf = f"{pre}-" if pre else ""
        gid = f"g{n}"
        defs.append(f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="0" y1="{y}" x2="0" y2="{y + S}">'
                    + "".join(f'<stop offset="{o}" stop-color="{hx(c)}"/>' for o, c in stops) + "</linearGradient>")
        f = f'fill="url(#{gid})"'
        st = f'fill="none" stroke="{hx(rim)}" stroke-width="1"'
        a, b = y + R, y + R + M                    # the rows where the corners end
        pieces = {
            "topleft": f'<path d="M0,{a} A{R},{R} 0 0 1 {R},{y} V{a} Z" {f}/><path d="M0.5,{a} A{R - 0.5},{R - 0.5} 0 0 1 {R},{y + 0.5}" {st}/>',
            "top": f'<rect x="{R}" y="{y}" width="{M}" height="{R}" {f}/><path d="M{R},{y + 0.5} H{R + M}" {st}/>',
            "topright": f'<path d="M{R + M},{y} A{R},{R} 0 0 1 {S},{a} H{R + M} Z" {f}/><path d="M{R + M},{y + 0.5} A{R - 0.5},{R - 0.5} 0 0 1 {S - 0.5},{a}" {st}/>',
            "left": f'<rect x="0" y="{a}" width="{R}" height="{M}" {f}/><path d="M0.5,{a} V{b}" {st}/>',
            "center": f'<rect x="{R}" y="{a}" width="{M}" height="{M}" {f}/>',
            "right": f'<rect x="{R + M}" y="{a}" width="{R}" height="{M}" {f}/><path d="M{S - 0.5},{a} V{b}" {st}/>',
            "bottomleft": f'<path d="M0,{b} H{R} V{y + S} A{R},{R} 0 0 1 0,{b} Z" {f}/><path d="M{R},{y + S - 0.5} A{R - 0.5},{R - 0.5} 0 0 1 0.5,{b}" {st}/>',
            "bottom": f'<rect x="{R}" y="{b}" width="{M}" height="{R}" {f}/><path d="M{R},{y + S - 0.5} H{R + M}" {st}/>',
            "bottomright": f'<path d="M{R + M},{b} H{S} A{R},{R} 0 0 1 {R + M},{y + S} Z" {f}/><path d="M{S - 0.5},{b} A{R - 0.5},{R - 0.5} 0 0 1 {R + M},{y + S - 0.5}" {st}/>',
        }
        out += [f'<g id="{pf}{k}">{v}</g>' for k, v in pieces.items()]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{S}" height="{len(element_prefixes) * (S + 4)}">'
            f"<defs>{''.join(defs)}</defs>{''.join(out)}</svg>\n")


def desktoptheme(ed):
    """The files of one Plasma style: {path: text}. What it leaves out falls back to Plasma's
    default style, drawn in the scheme's colours."""
    p = full(ed)
    shell = LOOK["shell"]
    chrome = [(0, p["chrome_top"]), (0.46, p["chrome_mid"]), (0.52, p["chrome_horizon"]), (0.84, p["chrome_low"]), (1, p["chrome_reflect"])]
    body = [(0, p["chrome_top"]), (0.12, p["shell"]), (1, mix(p["shell"], "#000000", 0.10))]
    return {
        "metadata.json": '{\n  "KPlugin": {\n    "Id": "fui-' + ed + '",\n    "Name": "fui ' + ed + '",\n'
                         '    "Description": "Round chrome shells for the panel and pop-ups (theme/kde.py)",\n'
                         '    "License": "MIT",\n    "Version": "1"\n  },\n  "X-Plasma-API-Minimum-Version": "6.0"\n}\n',
        "colors": colors(ed),
        "widgets/panel-background.svg": _shell_svg(p, shell, chrome, p["rim"], ("", "north", "south", "west", "east")),
        "dialogs/background.svg": _shell_svg(p, shell, body, p["rim"]),
        "widgets/tooltip.svg": _shell_svg(p, LOOK["radius"], [(0, p["raised"]), (1, p["panel"])], p["rim"]),
    }


def files():
    """Every generated KDE file: {path under the repo: text}."""
    out = {}
    for ed in EDS:
        out[f"kde/.local/share/color-schemes/{camel(ed)}.colors"] = colors(ed)
        for name, text in aurorae(ed).items():
            out[f"kde/.local/share/aurorae/themes/fui-{ed}/{name}"] = text
        for name, text in desktoptheme(ed).items():
            out[f"kde/.local/share/plasma/desktoptheme/fui-{ed}/{name}"] = text
    return out


